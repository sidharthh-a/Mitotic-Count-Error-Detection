"""Write the dataset audit report from measured values.

    python scripts/audit_dataset.py

Produces:
  docs/DATASET_AUDIT.md          human-readable audit
  data/metadata/audit.json       machine-readable facts

Everything printed here is read from the downloaded official files; nothing is copied
from the blueprint without being re-derived.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from midogcx.config import PROJECT_ROOT, load_config, resolve_path
from midogcx.data.metadata import build_index, filename_to_slide
from midogcx.data.splits import BLUEPRINT_COHORT, HISTORICAL_PILOT_SLIDES
from midogcx.utils import get_logger, save_json, sha256_file


def _fmt_bytes(n: float) -> str:
    return f"{n / 1024**3:.2f} GiB"


def main() -> int:
    log = get_logger("audit_dataset")
    cfg = load_config()
    meta_dir = resolve_path(cfg, "paths.manifest").parent
    manifest = resolve_path(cfg, "paths.manifest")
    annotations = resolve_path(cfg, "paths.annotations")

    index = build_index(manifest, annotations)
    audit = dict(index.audit)

    inventory_path = meta_dir / "dataset_inventory.csv"
    inventory = pd.read_csv(inventory_path) if inventory_path.exists() else None
    sizes = {}
    if inventory is not None:
        for _, row in inventory.iterrows():
            name = str(row.get("file_name"))
            if name.endswith(".tiff"):
                sizes[filename_to_slide(name)] = int(row["size_bytes"])

    cohort_rows = []
    for role, ids in BLUEPRINT_COHORT.items():
        rows = index.slides[index.slides["slide_id"].isin(ids)]
        cohort_rows.append(
            {
                "role": role,
                "n_specimens": len(rows),
                "n_positive_annotations": int(rows["n_positive"].sum()),
                "scanners": ", ".join(sorted(rows["scanner"].unique())),
                "origins": ", ".join(sorted(rows["origin"].unique())),
                "size_gib": round(sum(sizes.get(sid, 0) for sid in ids) / 1024**3, 2),
            }
        )
    cohort_frame = pd.DataFrame(cohort_rows)
    cohort_total = cohort_frame["size_gib"].sum()

    hashes = {}
    for label, path in (("manifest", manifest), ("annotations", annotations)):
        hashes[label] = {"path": str(path), "sha256": sha256_file(path), "bytes": path.stat().st_size}

    audit.update(
        {
            "file_hashes": hashes,
            "cohort": cohort_frame.to_dict(orient="records"),
            "cohort_total_gib": round(float(cohort_total), 2),
            "historical_pilot_slides": sorted(HISTORICAL_PILOT_SLIDES),
        }
    )
    save_json(audit, meta_dir / "audit.json")

    lines = [
        "# MIDOG++ Dataset Audit",
        "",
        "Generated by `scripts/audit_dataset.py` from the downloaded official files.",
        "Every number below is re-derived from `MIDOG++.json` and `datasets_xvalidation.csv`;",
        "nothing is copied from the research blueprint without verification.",
        "",
        "## Provenance",
        "",
        "| Source | Path | Bytes | SHA-256 |",
        "|---|---|---:|---|",
    ]
    for label, info in hashes.items():
        lines.append(
            f"| {label} | `{info['path']}` | {info['bytes']:,} | `{info['sha256'][:16]}...` |"
        )
    lines += [
        "",
        "Official sources: "
        "[repository](https://github.com/DeepMicroscopy/MIDOGpp), "
        "[collection](https://doi.org/10.6084/m9.figshare.c.6615571).",
        "",
        "## Verified counts",
        "",
        "| Quantity | Measured |",
        "|---|---:|",
        f"| Specimens in manifest (supervised eligibility) | {audit['n_manifest_slides']} |",
        f"| Image records in annotation JSON | {audit['n_json_images']} |",
        f"| JSON-only records without annotations | {audit['n_json_only_images']} |",
        f"| Annotations on those JSON-only records | {audit['n_annotations_on_json_only_images']} |",
        f"| Total annotations | {audit['n_annotations']} |",
        f"| Mitotic (category 1) | {audit['n_positive_annotations']} |",
        f"| Non-mitotic (category 2) | {audit['n_negative_annotations']} |",
        f"| Specimens with zero positives | {audit['n_slides_without_positive']} |",
        f"| Boxes with invalid geometry | {audit['n_bad_geometry_boxes']} |",
        f"| Annotation centres outside the image | {audit['n_out_of_bounds_centres']} |",
        "",
        f"Species: {audit['species_counts']}. Official split: {audit['official_split_counts']}.",
        "",
        "## Conventions used by this codebase",
        "",
        "* Filenames are the manifest id zero-padded to three digits (`094.tiff`). Row order",
        "  is never assumed to equal specimen id.",
        "* Bounding boxes are **xyxy**, verified against the SQLite export: `[4336, 346, 4386, 396]`",
        "  is a 50x50 box centred at `(4361, 371)`.",
        "* Category 1 = `mitotic figure` is the only positive class and maps to detector label 1",
        "  (torchvision RetinaNet reserves 0 for background). Category 2 = `not mitotic figure`",
        "  is a curated hard negative, never a second positive target.",
        "* Region labels use annotation *centres*, so each cell belongs to exactly one region.",
        "* Records `151.tiff`-`200.tiff` exist only in the JSON and carry no annotations. They",
        "  are excluded, never added as negative specimens.",
        "",
        "## Scanner labels",
        "",
        f"Raw spellings: {audit['scanner_raw_values']}",
        "",
        f"Normalised: {audit['scanner_normalized_values']}",
        "",
        "`Hamammatsu XR` (breast) and `Hamamatsu XR` (melanoma, neuroendocrine) are treated as",
        "one device. Evidence: identical origin, no specimen carries both spellings, and no",
        "other scanner model appears in those groups. This is a documented normalisation",
        "judgement, not a fact published by the dataset authors.",
        "",
        "## Proposed development cohort",
        "",
        "| Role | Specimens | Positive annotations | Scanner(s) | Origin(s) | Download size |",
        "|---|---:|---:|---|---|---:|",
    ]
    for row in cohort_frame.itertuples():
        lines.append(
            f"| {row.role} | {row.n_specimens} | {row.n_positive_annotations} | {row.scanners} | "
            f"{row.origins} | {row.size_gib} GiB |"
        )
    lines += [
        "",
        f"**Cohort download total: {cohort_total:.2f} GiB** (55 specimens). The full collection",
        "is 65.05 GiB over 506 files, so downloading everything is unnecessary and was not done.",
        "",
        "### Limitations recorded with the cohort",
        "",
        "1. The target domain (human melanoma) is single-origin (UMC Utrecht) and",
        "   single-scanner (Hamamatsu XR). Tumour-type adaptation is therefore confounded with",
        "   acquisition; results must not be described as isolated tumour-type effects.",
        "2. All 55 specimens are official **training** records. They are development data, not",
        "   official test data.",
        "3. Specimen separation is enforced, but the dataset does not expose patient",
        "   identifiers, so patient-level independence cannot be guaranteed.",
        "4. Equal annotated tissue area does not mean equal expert annotation time.",
        f"5. Previously downloaded pilot specimens {sorted(HISTORICAL_PILOT_SLIDES)} are excluded",
        "   from this cohort and can never serve as pristine assessment data.",
        "",
        "## Licensing",
        "",
        "The annotation JSON declares CC0 and the repository code is MIT-licensed. Code licence",
        "and dataset licence are separate; verify each Figshare item before redistribution.",
        "No private clinical data is used in logs or demonstrations.",
        "",
    ]

    out_path = PROJECT_ROOT / "docs" / "DATASET_AUDIT.md"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    log.info("wrote %s", out_path)
    print("\n".join(lines[:20]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
