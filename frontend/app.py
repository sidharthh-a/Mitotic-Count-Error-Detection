"""Streamlit demonstration interface.

    streamlit run frontend/app.py

It shows only what actually exists on disk: specimen images, regions generated by this
codebase, selections saved by a real experiment run, model detections from a real
checkpoint and metrics from a real evaluation file. When something is missing it says so
instead of inventing a plausible-looking number.

Nothing on this page is a clinical tool. Counts are research outputs on retrospective
MIDOG++ specimen images.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import streamlit as st

from midogcx.config import PROJECT_ROOT, load_config, resolve_path, resolve_specimen_path, resolve_data_root
from midogcx.data.images import read_geometry, read_rgb
from midogcx.data.metadata import build_index
from midogcx.data.splits import load_cohort
from midogcx.models.detector import read_checkpoint_meta

st.set_page_config(page_title="Count-error region selection — MIDOG++", layout="wide")


# --------------------------------------------------------------------------------------
# Cached loaders
# --------------------------------------------------------------------------------------
@st.cache_resource
def get_config():
    return load_config()


@st.cache_resource
def get_index(manifest: str, annotations: str):
    return build_index(manifest, annotations)


@st.cache_data
def get_regions(path: str) -> pd.DataFrame:
    p = Path(path)
    return pd.read_csv(p) if p.exists() else pd.DataFrame()


@st.cache_data
def get_geometry(path: str) -> pd.DataFrame:
    p = Path(path)
    return pd.read_csv(p) if p.exists() else pd.DataFrame()


@st.cache_resource
def get_model(checkpoint: str, device: str):
    from midogcx.models.detector import load_checkpoint

    model, payload = load_checkpoint(checkpoint, device=device)
    return model, payload


@st.cache_data(show_spinner=False)
def run_inference(checkpoint: str, slide_id: int, tile: int, stride: int, floor: float, device: str):
    from midogcx.inference.sliding_window import predict_slide

    model, payload = get_model(checkpoint, device)
    cfg = get_config()
    path = resolve_specimen_path(resolve_data_root(cfg), f"{slide_id:03d}.tiff")
    pred = predict_slide(
        model, path, tile=tile, stride=stride, batch_size=int(cfg["inference"]["batch_size"]),
        device=device, mean=payload["normalization"]["mean"], std=payload["normalization"]["std"],
        score_floor=floor, nms_radius_px=float(cfg["inference"]["nms_radius_px"]),
    )
    return pred.points, pred.scores


@st.cache_data(show_spinner=False)
def load_image(slide_id: int, max_side: int = 1600):
    cfg = get_config()
    path = resolve_specimen_path(resolve_data_root(cfg), f"{slide_id:03d}.tiff")
    geom = read_geometry(path)
    rgb = read_rgb(path)
    # Downsample for display only; all coordinates stay in native pixels.
    factor = max(1, int(np.ceil(max(rgb.shape[:2]) / max_side)))
    small = rgb[::factor, ::factor]
    return small, geom, factor


def list_checkpoints() -> list[Path]:
    root = resolve_path(get_config(), "project.outputs")
    return sorted(root.rglob("checkpoint*.pth"))


def list_experiments() -> list[Path]:
    root = resolve_path(get_config(), "project.outputs") / "experiments"
    if not root.exists():
        return []
    return sorted([p for p in root.iterdir() if p.is_dir()], reverse=True)


# --------------------------------------------------------------------------------------
# Drawing helpers
# --------------------------------------------------------------------------------------
def draw_overlay(rgb, factor, gt_points=None, pred_points=None, max_points=4000, title=""):
    fig, ax = plt.subplots(figsize=(11, 8))
    ax.imshow(rgb)
    if gt_points is not None and len(gt_points):
        ax.scatter(gt_points[:, 0] / factor, gt_points[:, 1] / factor, s=42, facecolors="none",
                   edgecolors="#00d1b2", linewidths=1.4, label=f"ground truth ({len(gt_points)})")
    if pred_points is not None and len(pred_points):
        shown = pred_points[:max_points]
        ax.scatter(shown[:, 0] / factor, shown[:, 1] / factor, s=16, c="#ff3860", marker="x",
                   linewidths=1.0, label=f"predicted ({len(pred_points)})")
    ax.set_title(title, fontsize=11)
    ax.legend(loc="lower right", fontsize=9)
    ax.axis("off")
    return fig


def draw_regions(rgb, factor, regions, selected_ids, title=""):
    from matplotlib.patches import Rectangle

    fig, ax = plt.subplots(figsize=(11, 8))
    ax.imshow(rgb)
    for r in regions:
        chosen = r["region_id"] in selected_ids
        ax.add_patch(
            Rectangle(
                (r["x"] / factor, r["y"] / factor),
                r["width"] / factor,
                r["height"] / factor,
                fill=chosen,
                facecolor="#3273dc" if chosen else "none",
                alpha=0.25 if chosen else 1.0,
                edgecolor="#3273dc" if chosen else "#b5b5b5",
                linewidth=1.6 if chosen else 0.7,
            )
        )
    ax.set_title(title, fontsize=11)
    ax.axis("off")
    return fig


# --------------------------------------------------------------------------------------
# Page
# --------------------------------------------------------------------------------------
cfg = get_config()
st.title("Count-Error-Guided Region Selection — MIDOG++")
st.caption(
    "Breast → melanoma cross-domain mitotic figure detection. Research prototype on "
    "retrospective specimen images; not a diagnostic device."
)

manifest = resolve_path(cfg, "paths.manifest")
annotations = resolve_path(cfg, "paths.annotations")
if not manifest.exists():
    st.error("Dataset metadata not found. Run `python scripts/audit_dataset_inventory.py` first.")
    st.stop()

index = get_index(str(manifest), str(annotations))
cohort_path = resolve_path(cfg, "paths.cohort")
cohort = load_cohort(cohort_path) if cohort_path.exists() else None
regions_path = resolve_path(cfg, "paths.regions")
regions_df = get_regions(str(regions_path))
geometry_df = get_geometry(str(regions_path.with_name("geometry.csv")))

data_root = resolve_data_root(cfg)
available = sorted(int(p.stem) for p in data_root.glob("*.tiff")) if data_root.exists() else []

sidebar = st.sidebar
sidebar.header("Data")
if not available:
    sidebar.warning(f"No specimen images under `{data_root}`.\nRun `scripts/download_specimens.py`.")
    st.info(
        "The dataset audit, cohort freeze and all tests run without images. This page needs "
        "specimens on disk to show real detections.\n\n"
        f"Expected location: `{data_root}` (override with `MIDOG_DATA_ROOT`)."
    )
    st.subheader("Dataset audit (real numbers)")
    st.json(index.audit)
    st.stop()

role_of = {sid: role for role, ids in (cohort.roles.items() if cohort else []) for sid in ids}
labels = [f"{sid:03d} — {role_of.get(sid, 'not in cohort')}" for sid in available]
choice = sidebar.selectbox("Specimen", labels)
slide_id = int(choice.split(" — ")[0])

checkpoints = list_checkpoints()
if not checkpoints:
    sidebar.error("No checkpoint found under `outputs/`.")
    st.warning("Train a detector first: `python scripts/train_detector.py`.")
    st.stop()

ckpt_choice = sidebar.selectbox("Checkpoint", [str(p.relative_to(PROJECT_ROOT)) for p in checkpoints])
ckpt_path = str(PROJECT_ROOT / ckpt_choice)

device = sidebar.selectbox("Device", ["cpu", "cuda"], index=0)
tile = sidebar.slider("Tile size", 256, 1024, int(cfg["inference"]["tile_size"]), step=128)
stride = sidebar.slider("Stride", 128, 1024, int(cfg["inference"]["stride"]), step=20)
threshold = sidebar.slider("Score threshold", 0.05, 0.95, 0.5, step=0.01)
show_gt = sidebar.checkbox("Show ground-truth annotations", value=True)

meta = read_checkpoint_meta(ckpt_path)
sidebar.caption(
    f"updates={meta['meta'].get('updates', '?')} · strategy={meta['meta'].get('strategy', 'source')}"
)

tab_det, tab_regions, tab_compare, tab_eval = st.tabs(
    ["Detections & count", "Region selection", "Strategy comparison", "Evaluation results"]
)

with tab_det:
    rgb, geom, factor = load_image(slide_id)
    col1, col2 = st.columns([3, 1])
    with col1:
        if st.button("Run inference", type="primary"):
            st.session_state["pred"] = run_inference(
                ckpt_path, slide_id, tile, stride, 0.01, device
            )
        pred = st.session_state.get("pred")
        if pred is None:
            st.info("Press **Run inference** to compute detections for this specimen.")
            st.pyplot(draw_overlay(rgb, factor, index.positives(slide_id) if show_gt else None,
                                   title=f"{slide_id:03d} · {geom.width}×{geom.height} px"))
        else:
            points, scores = pred
            keep = scores > threshold
            st.pyplot(draw_overlay(
                rgb, factor,
                index.positives(slide_id) if show_gt else None,
                points[keep],
                title=f"{slide_id:03d} · {geom.width}×{geom.height} px · threshold {threshold:.2f}",
            ))
    with col2:
        st.subheader("Counts")
        if pred is not None:
            points, scores = pred
            kept = int((scores > threshold).sum())
            gt = len(index.positives(slide_id))
            st.metric("Predicted mitoses", kept)
            st.metric("Ground-truth mitoses", gt)
            st.metric("Absolute count error", abs(kept - gt))
            st.caption("Raw detections after score filter; whole-specimen NMS applied.")
        st.divider()
        st.caption(
            f"spacing {geom.spacing_x_um:.4f} µm/px ({geom.spacing_source})\n\n"
            f"scale bar: 200 µm ≈ {200 / geom.spacing_x_um:.0f} px"
        )

with tab_regions:
    if regions_df.empty:
        st.info("No `data/splits/regions.csv` yet. Run `python scripts/prepare_regions.py`.")
    else:
        slide_regions = regions_df[regions_df["slide_id"] == slide_id]
        if slide_regions.empty:
            st.warning("This specimen has no generated regions (it may be outside the cohort).")
        else:
            experiments = list_experiments()
            selected_ids: set[str] = set()
            if experiments:
                exp_name = st.selectbox("Experiment", [p.name for p in experiments])
                run_dir = next(p for p in experiments if p.name == exp_name)
                sel_dir = run_dir / "selections"
                if sel_dir.exists():
                    strategy = st.selectbox("Strategy", sorted(p.stem for p in sel_dir.glob("*.json")))
                    import json

                    payload = json.loads((sel_dir / f"{strategy}.json").read_text(encoding="utf-8"))
                    selected_ids = {r["region_id"] for r in payload.get("selected_regions", [])}
                    used = payload.get("budget", {}).get("used_mm2")
                    st.caption(
                        f"{len(selected_ids)} regions selected · {used:.3f} mm² tissue · "
                        f"{sum(1 for _ in slide_regions[slide_regions['region_id'].isin(selected_ids)].itertuples())} in this specimen"
                    )
            else:
                st.info("No experiment run yet; showing the candidate pool only.")

            rgb, geom, factor = load_image(slide_id)
            st.pyplot(draw_regions(
                rgb, factor, slide_regions.to_dict("records"), selected_ids,
                title=f"{slide_id:03d} · {len(slide_regions)} candidate regions, "
                      f"{slide_regions['tissue_area_um2'].sum() / 1e6:.2f} mm² tissue",
            ))
            st.dataframe(
                slide_regions[["region_id", "x", "y", "tissue_area_um2", "n_positives"]]
                .assign(selected=lambda d: d["region_id"].isin(selected_ids))
                .head(50),
                use_container_width=True,
            )

with tab_compare:
    experiments = list_experiments()
    if not experiments:
        st.info("No experiment results yet. Run `scripts/run_acquisition_experiment.py` after training.")
    else:
        exp_name = st.selectbox("Experiment run", [p.name for p in experiments], key="cmp_exp")
        run = next(p for p in experiments if p.name == exp_name)
        cmp_path = run / "comparison.csv"
        if cmp_path.exists():
            st.subheader("Method comparison (independent melanoma assessment specimens)")
            st.dataframe(pd.read_csv(cmp_path), use_container_width=True)
        else:
            st.warning("This run has no comparison.csv yet.")

        overlap_path = run / "ranking_overlap.json"
        if overlap_path.exists():
            import json

            overlap = json.loads(overlap_path.read_text(encoding="utf-8"))["top20_overlap"]
            st.subheader("Top-20 selection overlap between strategies")
            st.dataframe(pd.DataFrame(overlap).T, use_container_width=True)
            st.caption("High overlap means a strategy is largely redundant with another.")

        pred_path = run / "predictor_report.json"
        if pred_path.exists():
            import json

            rep = json.loads(pred_path.read_text(encoding="utf-8"))
            st.subheader("Count-error predictor quality (out-of-fold)")
            st.json(rep)

with tab_eval:
    experiments = list_experiments()
    if not experiments:
        st.info("No evaluation results yet.")
    else:
        exp_name = st.selectbox("Evaluation run", [p.name for p in experiments], key="eval_exp")
        run = next(p for p in experiments if p.name == exp_name)
        metrics_dir = run / "metrics"
        metric_files = sorted(metrics_dir.glob("*.json")) if metrics_dir.exists() else []
        if not metric_files:
            st.warning("No metrics saved for this run.")
        else:
            method = st.selectbox("Method", [p.stem for p in metric_files])
            import json

            payload = json.loads(
                (metrics_dir / f"{method}.json").read_text(encoding="utf-8")
            )
            pooled = payload.get("pooled", {})
            counting = payload.get("counting", {})
            c1, c2, c3, c4 = st.columns(4)
            c1.metric("F1", f"{pooled.get('f1', float('nan')):.3f}")
            c2.metric("Precision", f"{pooled.get('precision', float('nan')):.3f}")
            c3.metric("Recall", f"{pooled.get('recall', float('nan')):.3f}")
            c4.metric("Count MAE", f"{counting.get('mae', float('nan')):.2f}")
            st.caption(
                "Counting error must be read with localisation: small count error can hide "
                "large FP/FN cancellation."
            )

            per = pd.DataFrame(payload.get("per_specimen", []))
            if not per.empty:
                st.subheader("Per-specimen results")
                st.dataframe(per, use_container_width=True)
                fig, ax = plt.subplots(figsize=(9, 3.6))
                ax.bar(per["slide_id"].astype(str), per["abs_count_error"], color="#3273dc")
                ax.set_ylabel("absolute count error")
                ax.set_xlabel("specimen id")
                ax.set_title(f"{method}: per-specimen counting error")
                plt.xticks(rotation=60)
                st.pyplot(fig)
